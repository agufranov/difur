/* синус-Гордон: два кинка навстречу (упруго отталкиваются) плюс пара
   антикинков-«статистов» вдали — они нужны только чтобы поле было периодическим */
const SG = (function () {
  const c1 = -0.2, c2 = -0.6;                 // оба горба влево, правый догоняет левый
  const G = (c: number) => 1/Math.sqrt(1 - c*c);
  const K = (x: number, x0: number, g: number) => 4*Math.atan(Math.exp( g*(x-x0)));
  const A = (x: number, x0: number)   => 4*Math.atan(Math.exp(-(x-x0))) - 2*Math.PI;   // неподвижные «статисты»
  const B = (x: number, x0: number, c: number) => -2*G(c)*c/Math.cosh(G(c)*(x-x0));    // ut кинка со скоростью c
  return {
    u:  (x: number) => K(x,-12,G(c1)) + K(x,0,G(c2)) + A(x,25) + A(x,45),
    ut: (x: number) => B(x,-12,c1) + B(x,0,c2) };
})();

/* φ⁴: стенка и антистенка на ±12 идут навстречу со скоростью V. Ниже критической
   (V ≈ 0.26) пара захватывается, выше — расходится; порог и есть весь сюжет,
   поэтому это три сценария одного уравнения, а не три пресета. Замерено по нулям
   поля при t = 0/30/55/70/100 (L=60, N=512, dt=0.004):
     V=0.20 → ±12, ±6, слились, ±0.8, ±5.8      — захват и переизлучение
     V=0.26 → ±12, ±4.2, ±2.9, ±3.6, ±4.3       — связанная пара, бьётся
     V=0.30 → ±12, ±3.0, ±4.1, ±6.2, ±10.4      — разошлись
   `-1` в `u` сдвигает пузырь на фон −1: вне пары поле сидит в другой яме. */
const PHI4 = (V: number) => {
  const g = 1/Math.sqrt(1 - V*V), X = 12, s = Math.SQRT2;
  const K = (x: number, x0: number) => Math.tanh(g*(x - x0)/s);
  const B = (x: number, x0: number) => -(g*V/s)/Math.pow(Math.cosh(g*(x - x0)/s), 2);
  return { u: (x: number) => K(x, -X) - K(x, X) - 1,
           ut: (x: number) => B(x, -X) + B(x, X) };
};
const P4a = PHI4(0.20), P4b = PHI4(0.26), P4c = PHI4(0.30);

/* плато скорости шире горба — горб едет как твёрдое тело */
