/* ================= пресеты ================= */

/** начальные данные одного поля: инструмент с параметрами или явная функция */
export interface ICDesc {
  tool?: string; A?: number; w?: number; x0?: number; base?: number; edge?: number;
  k0?: number;
  fn?: (x: number, L: number) => number;
  fnRe?: (x: number, L: number) => number;
  fnIm?: (x: number, L: number) => number;
}

export interface Scenario {
  name: string; icon: string; tip: string;
  ic: Record<string, ICDesc>;
  k0?: number; N?: number; y?: [number, number]; pad?: number;
}

export interface Preset {
  name: string; eq: string; L: number; N: number; dt: number; y: [number, number];
  p?: Record<string, number>;
  ic?: Record<string, ICDesc>;
  sc?: Scenario[];
  sol?: boolean; story?: boolean; smooth?: boolean; fixdt?: boolean;
  /** запас за окном: кольцо в pad раз длиннее того, что видно (1, 2, 4) */
  pad?: number;
  spf?: number; vis?: Record<string, boolean>; sel?: string;
}

