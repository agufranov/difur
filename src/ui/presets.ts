/* синус-Гордон: два кинка навстречу (упруго отталкиваются) плюс пара
   антикинков-«статистов» вдали — они нужны только чтобы поле было периодическим */
const SG = (function () {
  const c1 = -0.2, c2 = -0.6;                 // оба горба влево, правый догоняет левый
  const G = (c: number) => 1/Math.sqrt(1 - c*c);
  const K = (x: number, x0: number, g: number) => 4*Math.atan(Math.exp( g*(x-x0)));
  const A = (x: number, x0: number)   => 4*Math.atan(Math.exp(-(x-x0))) - 2*Math.PI;   // неподвижные «статисты»
  const B = (x: number, x0: number, c: number) => -2*G(c)*c/Math.cosh(G(c)*(x-x0));    // ut кинка со скоростью c
  return {
    u:  (x: number) => K(x,-12,G(c1)) + K(x,0,G(c2)) + A(x,25) + A(x,45),
    ut: (x: number) => B(x,-12,c1) + B(x,0,c2) };
})();

/* плато скорости шире горба — горб едет как твёрдое тело */
const plateau = (x: number, x0: number, w: number, e: number) =>
  0.5*(Math.tanh((x-x0+w)/e) - Math.tanh((x-x0-w)/e));

